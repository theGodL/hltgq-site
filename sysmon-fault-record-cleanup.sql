-- 核对备份行数：正常 bak_rows 与 main_rows 相等；应用运行中主表可能略多几行新故障
SELECT (SELECT COUNT(*) FROM "qixiao-apaas"."t_auto_hltgq_sys_fault_record") AS main_rows,
       (SELECT COUNT(*) FROM "qixiao-apaas".t_auto_hltgq_sys_fault_record_bak20261029) AS bak_rows;

